function currentLanguage() {
  // The renderer's locale follows the macOS application language.
  const locale = (typeof navigator !== 'undefined' && navigator.language) ||
    (typeof Intl !== 'undefined' && Intl.DateTimeFormat().resolvedOptions().locale) || 'en';
  return /^el(?:-|$)/i.test(locale) ? 'el' : 'en';
}

function translateMenu(items, language = currentLanguage()) {
  if (language !== 'el') return items;
  if (Array.isArray(items)) return items.map(item => translateMenu(item, language));
  if (!items || typeof items !== 'object') return items;
  const result = Object.assign({}, items);
  if (typeof result.label === 'string' && Object.prototype.hasOwnProperty.call(greek, result.label)) {
    result.label = greek[result.label];
  }
  if (result.submenu) result.submenu = translateMenu(result.submenu, language);
  return result;
}

